package ex_26_Wrapper_Class;

public class Lab210_Wrapper_Conversion {

    public static void main(String[] args) {
        int a =10;
        // a. // no attribute
        // a.len() // no method
        Integer a1 = 10; // Wrapped Data Type
        System.out.println(Integer.MAX_VALUE); //attribute of Integer
        System.out.println(a1.intValue()); // behaviour of Integer
    }
}

